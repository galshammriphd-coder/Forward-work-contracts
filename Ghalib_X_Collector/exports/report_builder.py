"""Builds the content of an analytical report from the stored data.

Every number and every conclusion sentence below is computed from the posts in
the database for the chosen scope; nothing is generated by a language model.
"""
from __future__ import annotations

import pandas as pd

from analytics import statistics as st
from analytics.sentiment import LABELS_AR, analyze_posts, stored_sentiment
from analytics.summarization import extractive_summary
from analytics.topic_modeling import extract_keywords, run_topic_model
from database import db, models
from processing.language_detection import language_name


def _fmt(n) -> str:
    if n is None or (isinstance(n, float) and pd.isna(n)):
        return "غير متاح"
    if isinstance(n, float):
        return f"{n:,.1f}"
    return f"{int(n):,}"


def build_report(title: str, job_ids: list[int] | None = None, date_from=None, date_to=None,
                 languages: list[str] | None = None, keyword: str | None = None, n_topics: int = 5) -> dict:
    df = st.load_posts(job_ids=job_ids, date_from=date_from, date_to=date_to, languages=languages, keyword=keyword)
    jobs = [models.get_job(j) for j in (job_ids or [])]
    jobs = [j for j in jobs if j]
    rep: dict = {
        "title": title,
        "generated_at": db.utcnow(),
        "scope": {"jobs": [f"#{j['id']} {j['name']}" for j in jobs] or ["كل البيانات"],
                  "date_from": str(date_from or "—"), "date_to": str(date_to or "—"),
                  "languages": languages or ["الكل"], "keyword": keyword or "—"},
        "jobs": [{"id": j["id"], "name": j["name"], "type": models.SEARCH_TYPE_LABELS_AR.get(j["search_type"], j["search_type"]),
                  "query": j["query_text"], "queries": " | ".join(j["queries"]), "status": models.STATUS_LABELS_AR.get(j["status"]),
                  "created_at": j["created_at"], "received": j["received_count"], "new": j["new_count"],
                  "duplicates": j["duplicate_count"], "processed": j["processed_count"]} for j in jobs],
        "n_posts": len(df),
    }
    if df.empty:
        rep["empty"] = True
        rep["conclusions"] = ["لا توجد منشورات مطابقة لنطاق التقرير."]
        return rep
    k = st.kpis(df)
    totals = st.metric_totals(df)
    rep["kpis"] = k
    rep["metric_totals"] = totals
    rep["timeline"] = st.posts_over_time(df, "D")
    lang = st.language_distribution(df)
    lang["language"] = lang["lang"].map(language_name)
    rep["languages"] = lang
    rep["top_hashtags"] = st.top_hashtags(df, 15)
    rep["top_accounts"] = st.top_accounts(df, 15)
    rep["top_words"] = st.top_words(df, 25)
    rep["engagement_dist"] = st.engagement_distribution(df)
    try:
        rep["keywords"] = extract_keywords(df, 20)
    except Exception:
        rep["keywords"] = pd.DataFrame(columns=["keyword", "score", "documents"])

    sent = stored_sentiment(df["post_id"].tolist())
    engine_note = "نتائج محفوظة من صفحة التحليلات"
    missing = set(df["post_id"]) - set(sent["post_id"]) if not sent.empty else set(df["post_id"])
    if missing:
        fresh = analyze_posts(df[df["post_id"].isin(missing)], engine="lexicon", store=True)
        sent = pd.concat([sent[["post_id", "label"]] if not sent.empty else pd.DataFrame(columns=["post_id", "label"]),
                          fresh[["post_id", "label"]]])
        engine_note = "المحرك المعجمي المدمج (خط أساس) للسجلات غير المحللة مسبقاً"
    sd = sent["label"].value_counts().reindex(["positive", "neutral", "negative", "mixed"]).fillna(0).astype(int)
    rep["sentiment"] = pd.DataFrame({"label": sd.index, "label_ar": [LABELS_AR[x] for x in sd.index], "posts": sd.values})
    rep["sentiment_note"] = engine_note

    try:
        tm = run_topic_model(df, n_topics=n_topics, store=True)
        rep["topics"] = pd.DataFrame([{"topic": t["topic_id"] + 1, "label": t["label"], "keywords": ", ".join(t["keywords"]),
                                       "posts": t["posts"]} for t in tm["topics"]]).sort_values("posts", ascending=False)
        rep["topics_note"] = f"TF-IDF + NMF ({n_topics} موضوعات)"
    except ValueError as exc:
        rep["topics"] = pd.DataFrame(columns=["topic", "label", "keywords", "posts"])
        rep["topics_note"] = str(exc)
    rep["highlights"] = extractive_summary(df, k=5)
    rep["conclusions"] = conclusions(df, rep)
    return rep


def conclusions(df: pd.DataFrame, rep: dict) -> list[str]:
    out = []
    k = rep["kpis"]
    days = df["published_date"].dropna()
    span = f"بين {days.min()} و {days.max()}" if not days.empty else ""
    out.append(f"شمل التقرير {_fmt(k['total_posts'])} منشوراً من {_fmt(k['unique_accounts'])} حساباً {span}.")
    tl = rep["timeline"]
    if not tl.empty and tl["posts"].max() > 0:
        peak = tl.loc[tl["posts"].idxmax()]
        out.append(f"بلغ النشاط ذروته يوم {pd.Timestamp(peak['period']).date()} بعدد {int(peak['posts'])} منشوراً.")
    lang = rep["languages"]
    if not lang.empty:
        top = lang.iloc[0]
        out.append(f"اللغة الغالبة: {top['language']} بنسبة {top['posts'] / len(df) * 100:.1f}٪ من المنشورات.")
    th = rep["top_hashtags"]
    if not th.empty:
        out.append("أبرز الوسوم: " + "، ".join(th["hashtag"].head(5)) + ".")
    ta = rep["top_accounts"]
    if not ta.empty:
        share = ta["posts"].head(10).sum() / len(df) * 100
        out.append(f"أكثر الحسابات نشاطاً: @{ta.iloc[0]['username']} ({int(ta.iloc[0]['posts'])} منشور)، "
                   f"وتمثل أعلى 10 حسابات {share:.1f}٪ من المنشورات.")
    if k.get("avg_engagement") is not None:
        out.append(f"متوسط التفاعل (ردود + إعادة نشر + إعجابات + اقتباسات) لكل منشور: {_fmt(k['avg_engagement'])} "
                   f"محسوباً على {_fmt(k['engagement_available'])} منشوراً توفرت عداداته.")
    s = rep["sentiment"]
    if s["posts"].sum():
        top = s.sort_values("posts", ascending=False).iloc[0]
        pos = int(s.loc[s.label == "positive", "posts"].sum())
        neg = int(s.loc[s.label == "negative", "posts"].sum())
        out.append(f"الاتجاه العام للمشاعر: {top['label_ar']} ({top['posts'] / s['posts'].sum() * 100:.1f}٪)، "
                   f"ونسبة الإيجابي إلى السلبي {pos}:{neg}.")
    t = rep["topics"]
    if not t.empty:
        out.append("الموضوعات الرئيسية المكتشفة: " + " / ".join(t["label"].head(3)) + ".")
    dup = df["validation_notes"].fillna("").str.contains("duplicate_text_of").sum()
    if dup:
        out.append(f"رُصد {int(dup)} منشوراً بنص مكرر لمنشورات سابقة (قد يشير إلى نشر منسق أو إعادة نسخ).")
    return out
